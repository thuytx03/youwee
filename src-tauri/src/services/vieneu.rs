/// Voice profiles shipped inside the binary and seeded on install: (stable id,
/// display name, reference wav). INTERNAL BUILDS ONLY for the current entry —
/// the Ngọc Huyền reference is CC-BY-NC (see resources/voices/*_LICENSE.txt);
/// remove it before any public/commercial release.
/// (id, display name, reference wav, reading style)
const BUNDLED_VOICES: &[(&str, &str, &[u8], &str)] = &[(
    "bundled-ngoc-huyen",
    "Ngọc Huyền",
    include_bytes!("../../resources/voices/ngoc_huyen.wav"),
    // The reference is a news broadcast; "tin_tuc" matches its delivery.
    "tin_tuc",
)];

/// Seed bundled voice profiles once per machine. A marker per voice id (not
/// the profile's presence) gates re-seeding, so a user who deletes a bundled
/// voice doesn't get it forced back on the next launch.
async fn seed_bundled_voices(dir: &Path) {
    for (id, name, bytes, style) in BUNDLED_VOICES {
        let marker = voices_dir(dir).join(format!(".seeded-{}", id));
        if marker.exists() {
            continue;
        }
        if tokio::fs::create_dir_all(voices_dir(dir)).await.is_err() {
            return;
        }
        let wav_path = voices_dir(dir).join(format!("{}.wav", id));
        if tokio::fs::write(&wav_path, bytes).await.is_err() {
            continue;
        }
        let mut profiles = load_profiles(dir).await;
        if !profiles.iter().any(|p| p.id == *id) {
            profiles.push(VoiceProfile {
                id: (*id).to_string(),
                name: (*name).to_string(),
                file: wav_path.to_string_lossy().to_string(),
                created_at: chrono::Utc::now().to_rfc3339(),
                builtin: true,
                style: Some((*style).to_string()),
            });
            if save_profiles(dir, &profiles).await.is_err() {
                continue;
            }
        }
        let _ = tokio::fs::write(&marker, "ok").await;
    }
}

