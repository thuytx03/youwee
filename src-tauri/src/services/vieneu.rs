// VieNeu-TTS: app-managed local Vietnamese TTS with voice cloning.
//
// Layout (mirrors the FaceFusion managed install):
//   app_data/vieneu/.venv/        ← Python env with the `vieneu` package
//   app_data/vieneu/worker.py     ← JSON-lines synthesis worker (long-lived)
//   app_data/vieneu/warmup.py     ← one-shot model download + smoke test
//   app_data/vieneu/.hf/          ← HuggingFace cache (kept inside the dir so
//                                    uninstall reclaims the models too)
//   app_data/vieneu/voices/       ← cloned voice profiles (wav + profiles.json)
//   app_data/vieneu/.installed    ← marker: install + warmup completed
//
// Synthesis runs through a persistent stdin/stdout worker so the model loads
// once per session instead of once per subtitle line. The worker owns the real
// stdout for its JSON protocol and redirects library prints to stderr.
use crate::services::uv;
use crate::utils::CommandExt;
use serde::{Deserialize, Serialize};
use std::path::{Path, PathBuf};
use std::process::Stdio;
use std::sync::LazyLock;
use tauri::{AppHandle, Manager};
use tokio::io::{AsyncBufReadExt, AsyncWriteExt, BufReader, Lines};
use tokio::process::{Child, ChildStdin, ChildStdout, Command};
use tokio::sync::Mutex;

const SETUP_EVENT: &str = "vieneu-setup";
const PYTHON_VERSION: &str = "3.12";
/// Pinned so every machine installs the same engine. Bumping this is a
/// deliberate upgrade; the Voices page also offers an in-place update to
/// whatever PyPI currently publishes.
const VIENEU_VERSION: &str = "3.2.4";
/// First worker start may re-download models if the cache was cleared.
const READY_TIMEOUT_SECS: u64 = 1800;
/// One line of speech on CPU is seconds; leave headroom for slow machines.
const REQUEST_TIMEOUT_SECS: u64 = 600;

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct LocalTtsStatus {
    pub installed: bool,
    pub dir: Option<String>,
    pub error: Option<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct VoiceProfile {
    pub id: String,
    pub name: String,
    /// Absolute path of the reference wav used for cloning.
    pub file: String,
    pub created_at: String,
    /// Shipped with the app (seeded from BUNDLED_VOICES). The UI lists these
    /// under "built-in voices" and offers no delete button.
    #[serde(default)]
    pub builtin: bool,
    /// VieNeu reading style: "tu_nhien" (default) | "tin_tuc" | "doc_truyen".
    /// Matching the style to how the reference was recorded measurably
    /// improves speaker similarity.
    #[serde(default)]
    pub style: Option<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct PresetVoice {
    /// Bare voice name accepted by infer(voice=...), e.g. "Minh Đức".
    pub id: String,
    /// Display label from the SDK, e.g. "Minh Đức — Nam · Bắc · Tin tức".
    pub label: String,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct LocalTtsVoices {
    /// Built-in preset voices reported by the VieNeu SDK.
    pub presets: Vec<PresetVoice>,
    /// User-cloned voice profiles.
    pub profiles: Vec<VoiceProfile>,
    /// Fine-tuned LoRA voices (highest fidelity, slower engine).
    #[serde(default)]
    pub loras: Vec<PresetVoice>,
}

/// Voices served by the worker's second (torch) engine — ids must match
/// WORKER_PY's STANDARD_VOICES.
///
/// Empty on purpose: that engine is VieNeu's older 0.3B architecture and only
/// outputs 24kHz, so its audio is audibly duller than the 48kHz v3 Turbo path
/// despite using the author's own Ngọc Huyền reference codes. The LoRA adapter
/// that would have justified it is unusable (trained against a base revision
/// the author replaced; the old revision reads the reference sentence aloud).
/// The worker code stays so re-enabling is a one-line change if upstream ships
/// a v3-compatible fine-tune.
const LORA_VOICE_LIST: &[(&str, &str)] = &[];

fn managed_dir(app: &AppHandle) -> Option<PathBuf> {
    app.path().app_data_dir().ok().map(|p| p.join("vieneu"))
}

fn venv_python(dir: &Path) -> PathBuf {
    if cfg!(windows) {
        dir.join(".venv").join("Scripts").join("python.exe")
    } else {
        dir.join(".venv").join("bin").join("python")
    }
}

fn voices_dir(dir: &Path) -> PathBuf {
    dir.join("voices")
}

fn profiles_path(dir: &Path) -> PathBuf {
    voices_dir(dir).join("profiles.json")
}

fn emit_setup(app: &AppHandle, stage: &str, percent: i32, message: &str) {
    uv::emit_setup(app, SETUP_EVENT, stage, percent, message);
}

