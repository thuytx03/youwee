const WORKER_PY: &str = r#"# Auto-generated by Youwee. JSON-lines worker for VieNeu local TTS.
import json
import os
import sys

# The vieneu library (and its deps) may print to stdout; the JSON protocol
# must own the real stdout, so keep a private handle and route prints to stderr.
proto = os.fdopen(os.dup(1), "w", buffering=1)
sys.stdout = sys.stderr


def preset_entry(v):
    # list_preset_voices() entries vary by SDK version: plain names, dicts, or
    # (display label, voice name) tuples. Normalize to {id, label} where id is
    # what infer(voice=...) accepts.
    if isinstance(v, (list, tuple)) and v:
        return {"id": str(v[-1]), "label": str(v[0]) or str(v[-1])}
    if isinstance(v, dict):
        name = str(v.get("name") or v.get("id") or v)
        return {"id": name, "label": str(v.get("label") or name)}
    s = str(v)
    return {"id": s, "label": s}


# High-fidelity voices served by the "standard" (torch) engine, keyed by id.
#
# `codes_repo` supplies the reference codes+text (published in a voices.json);
# for Ngọc Huyền those live in the author's LoRA repo. The LoRA ADAPTER itself
# is deliberately NOT loaded: it was trained against a base revision the author
# has since replaced, and pinning that dead revision produces broken audio —
# the model reads the reference sentence aloud and rambles for 15-25s. Using
# the current base with these reference codes is both correct and fast
# (~3s of audio in ~4s), and still reproduces the target voice.
STANDARD_VOICES = {
    "ngoc-huyen": {
        "base": "pnnbao-ump/VieNeu-TTS-0.3B",
        "codes_repo": "pnnbao-ump/VieNeu-TTS-0.3B-lora-ngoc-huyen",
        "preset": "NgocHuyen",
    }
}


def standard_synthesize(std, voice_id, text, out):
    cfg = STANDARD_VOICES[voice_id]
    if std["engine"] is None:
        # This engine's model is NOT fetched during install, so it needs the
        # Hub on first use — lift the worker's offline default just for it.
        os.environ.pop("HF_HUB_OFFLINE", None)
        from vieneu import Vieneu

        device = "cpu"
        try:
            import torch

            if torch.backends.mps.is_available():
                device = "mps"
            elif torch.cuda.is_available():
                device = "cuda"
        except Exception:
            pass
        std["engine"] = Vieneu(
            mode="standard",
            backbone_repo=cfg["base"],
            gguf_filename=None,
            backbone_device=device,
            codec_device="cpu",
        )
    voice = std["voices"].get(voice_id)
    if voice is None:
        import json as _json

        from huggingface_hub import hf_hub_download

        preset = _json.load(open(hf_hub_download(cfg["codes_repo"], "voices.json")))["presets"][
            cfg["preset"]
        ]
        try:
            import torch

            codes = torch.tensor(preset["codes"], dtype=torch.long)
        except ImportError:
            import numpy as np

            codes = np.array(preset["codes"], dtype=np.int64)
        voice = {"codes": codes, "text": preset["text"]}
        std["voices"][voice_id] = voice
    audio = std["engine"].infer(text, voice=voice)
    std["engine"].save(audio, out)


def main():
    from vieneu import Vieneu

    # Engine precision comes from engine.json (written by the app): "int8" is
    # the fast default, "fp32" trades ~15% speed for noticeably closer voice
    # reproduction. Both are the same 48kHz v3 Turbo model.
    precision = "int8"
    try:
        with open("engine.json", encoding="utf-8") as fh:
            precision = (json.load(fh).get("precision") or "int8").lower()
    except Exception:
        pass
    if precision not in ("int8", "fp32"):
        precision = "int8"

    tts = Vieneu(precision=precision)
    # Lazy second engine for the high-fidelity voices; not loaded until asked.
    std = {"engine": None, "voices": {}}
    # Reference voices registered this session: (path, mtime) -> internal name.
    # add_voice() encodes the reference ONCE (the slow part, several seconds);
    # every later synthesis with that voice then runs at preset speed instead
    # of re-encoding the reference audio on every single request.
    registered = {}
    proto.write(json.dumps({"event": "ready"}) + "\n")
    for line in sys.stdin:
        line = line.strip()
        if not line:
            continue
        rid = None
        try:
            req = json.loads(line)
            rid = req.get("id")
            op = req.get("op")
            if op == "voices":
                try:
                    voices = [preset_entry(v) for v in (tts.list_preset_voices() or [])]
                except Exception:
                    voices = []
                proto.write(
                    json.dumps({"id": rid, "ok": True, "voices": voices}, ensure_ascii=False) + "\n"
                )
            elif op == "tts" and req.get("lora"):
                voice_id = req["lora"]
                if voice_id not in STANDARD_VOICES:
                    proto.write(json.dumps({"id": rid, "ok": False, "error": "unknown hq voice"}) + "\n")
                    continue
                standard_synthesize(std, voice_id, req["text"], req["out"])
                proto.write(
                    json.dumps({"id": rid, "ok": True, "path": req["out"]}, ensure_ascii=False) + "\n"
                )
            elif op == "tts":
                kwargs = {}
                if req.get("ref_audio"):
                    ref = req["ref_audio"]
                    denoise = bool(req.get("denoise", True))
                    try:
                        key = (ref, os.path.getmtime(ref))
                    except OSError:
                        key = (ref, 0)
                    style = req.get("style") or "tu_nhien"
                    name = registered.get(key)
                    if name is None:
                        try:
                            name = "__ref_%d" % len(registered)
                            tts.add_voice(name, ref, denoise=denoise, style=style)
                            registered[key] = name
                        except Exception:
                            name = None
                    if name is not None:
                        kwargs["voice"] = name
                    else:
                        # Registration failed — fall back to the per-request path.
                        kwargs["ref_audio"] = ref
                        kwargs["denoise"] = denoise
                    kwargs["style"] = style
                elif req.get("voice"):
                    kwargs["voice"] = req["voice"]
                # VieNeu stamps an inaudible watermark by default; skipping it
                # measurably improves speaker similarity and this audio never
                # leaves the user's machine unattributed.
                kwargs["apply_watermark"] = False
                audio = tts.infer(req["text"], **kwargs)
                tts.save(audio, req["out"])
                proto.write(
                    json.dumps({"id": rid, "ok": True, "path": req["out"]}, ensure_ascii=False) + "\n"
                )
            elif op == "ping":
                proto.write(json.dumps({"id": rid, "ok": True}) + "\n")
            else:
                proto.write(json.dumps({"id": rid, "ok": False, "error": "unknown op"}) + "\n")
        except Exception as exc:  # keep serving after a bad request
            import traceback

            traceback.print_exc()
            proto.write(
                json.dumps({"id": rid, "ok": False, "error": str(exc)}, ensure_ascii=False) + "\n"
            )


if __name__ == "__main__":
    main()
"#;

